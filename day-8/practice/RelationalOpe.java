class RelationalOpe{
	
	public static void main(String args[]){
		
		//assignment operator
		int num1 = 185000;
		int num2 = 100000;
		
		System.out.println("Num1  :" + num1);
		System.out.println("Num2  :" + num2);
		System.out.println("Operator > :" + (num1>num2));
		System.out.println("Operator < :" + (num1<num2));
		System.out.println("Operator >= :" + (num1>=num2));
		System.out.println("Operator <= :" + (num1<=num2));
		System.out.println("Operator == :" + (num1==num2));
		System.out.println("Operator != :" + (num1!=num2));
		
	}
	
}